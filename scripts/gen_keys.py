#!/usr/bin/env python3
"""Step 1 (enrollment): generate the keys shared by the fob and car firmware.

Writes common/keys.h, which both builds include. Flash both boards from the
same keys.h: a fob and a car built from different files will never pair.
"""

import argparse
import secrets
import sys
from pathlib import Path

KEYS_H = Path(__file__).resolve().parent.parent / "common" / "keys.h"


def c_array(data: bytes) -> str:
    return "{ " + ", ".join(f"0x{b:02x}" for b in data) + " }"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true",
                        help="overwrite an existing keys.h (re-flash both boards afterwards)")
    args = parser.parse_args()

    if KEYS_H.exists() and not args.force:
        print(f"{KEYS_H} already exists; use --force to replace it", file=sys.stderr)
        return 1

    secret = secrets.token_bytes(32)
    irk = secrets.token_bytes(16)
    # Static random address, stored little-endian like bt_addr_t: the two
    # most significant bits of the last byte must be 0b11.
    id_addr = bytearray(secrets.token_bytes(6))
    id_addr[5] |= 0xC0

    KEYS_H.write_text(f"""\
/* Generated by scripts/gen_keys.py. Do not commit: these are the pairing keys. */
#ifndef PKE_KEYS_H
#define PKE_KEYS_H

/* Shared secret for the challenge-response and session key derivation. */
#define PKE_SHARED_SECRET_INIT {c_array(secret)}

/* Fob Identity Resolving Key, in the byte order bt_id_create() takes. */
#define PKE_FOB_IRK_INIT {c_array(irk)}

/* Fob static random identity address, little-endian as in bt_addr_t. */
#define PKE_FOB_ID_ADDR_INIT {c_array(bytes(id_addr))}

#endif /* PKE_KEYS_H */
""")
    print(f"wrote {KEYS_H}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
